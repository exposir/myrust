//! TypeScript client generation for registered IPC channels.

use std::{collections::BTreeMap, fs, path::Path};

use anyhow::{Context, Result};

use super::IpcRouter;

/// Generates `frontend/myrust.d.ts`-style declarations from an IPC router.
pub struct TypeScriptGenerator;

impl TypeScriptGenerator {
    /// Renders TypeScript declarations and typed invocation helpers.
    pub fn generate(router: &IpcRouter, app_name: &str) -> String {
        let channels = router.schema();
        let mut declarations = BTreeMap::<&'static str, &'static str>::new();

        for channel in &channels {
            if !channel.request_type.is_empty() && !channel.request_declaration.is_empty() {
                declarations.insert(channel.request_type, channel.request_declaration);
            }
            if !channel.response_type.is_empty() && !channel.response_declaration.is_empty() {
                declarations.insert(channel.response_type, channel.response_declaration);
            }
        }

        let mut output = String::new();
        output.push_str(&format!(
            "// Generated by myrust-core for {app_name}. Do not edit manually.\n\n"
        ));
        output.push_str("export interface IpcError {\n  code: number;\n  message: string;\n}\n\n");
        output.push_str(
            "export interface IpcBridge {\n  invoke<T = unknown>(channel: string, payload?: unknown): Promise<T>;\n  on<T = unknown>(channel: string, listener: (payload: T) => void): () => void;\n}\n\n",
        );
        output.push_str(
            "declare global {\n  interface Window {\n    __myrust_ipc__?: IpcBridge;\n  }\n}\n\n",
        );
        output.push_str("export const ipc = window.__myrust_ipc__ as IpcBridge;\n\n");

        for declaration in declarations.values() {
            output.push_str(declaration.trim());
            output.push_str("\n\n");
        }

        if channels.is_empty() {
            output.push_str("// No IPC channels are registered.\n");
            return output;
        }

        let channel_names = channels
            .iter()
            .map(|channel| format!("\"{}\"", channel.channel))
            .collect::<Vec<_>>()
            .join(" | ");
        output.push_str(&format!("export type IpcChannel = {channel_names};\n\n"));

        for channel in channels {
            if !channel.description.is_empty() {
                output.push_str(&format!(
                    "/** {} */\n",
                    channel.description.replace('\n', " ")
                ));
            }

            let function_name = to_camel_case(&channel.channel);
            if channel.request_type == "undefined" {
                output.push_str(&format!(
                    "export const {function_name} = () => ipc.invoke<{}>(\"{}\");\n\n",
                    channel.response_type, channel.channel
                ));
            } else {
                output.push_str(&format!(
                    "export const {function_name} = (payload: {}) => ipc.invoke<{}>(\"{}\", payload);\n\n",
                    channel.request_type, channel.response_type, channel.channel
                ));
            }
        }

        output
    }

    /// Writes generated TypeScript declarations to `path`.
    pub fn write(router: &IpcRouter, app_name: &str, path: impl AsRef<Path>) -> Result<()> {
        let path = path.as_ref();
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("failed to create {}", parent.display()))?;
        }
        fs::write(path, Self::generate(router, app_name))
            .with_context(|| format!("failed to write {}", path.display()))
    }
}

fn to_camel_case(channel: &str) -> String {
    let mut result = String::new();
    let mut uppercase_next = false;

    for (index, character) in channel.chars().enumerate() {
        if character == '_' || character == '-' || character == ' ' {
            uppercase_next = !result.is_empty();
            continue;
        }

        if result.is_empty() && !character.is_ascii_alphabetic() && character != '_' {
            result.push('_');
        }

        if uppercase_next {
            result.push(character.to_ascii_uppercase());
            uppercase_next = false;
        } else if index == 0 {
            result.push(character.to_ascii_lowercase());
        } else {
            result.push(character);
        }
    }

    if result.is_empty() {
        "invokeChannel".to_string()
    } else {
        result
    }
}
